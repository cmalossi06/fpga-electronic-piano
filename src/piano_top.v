`timescale 1ns / 1ps
//==============================================================================
// piano_top.v
//------------------------------------------------------------------------------
// 8-note electronic piano - top level (Nexys A7 / Artix-7, 100 MHz clock).
//
// Implements all five system requirements of Topic 2:
//   1. 8 keys, one per standard tone (do, re, mi, fa, sol, la, si, high do).
//   2. A square wave at the exact tone frequency is produced for each key.
//   3. A passive buzzer plays the tone and an LED flashes in sync with it.
//   4. No buzzer or LED output when no key is pressed.
//   5. Tone frequencies are generated by a digital frequency-division module.
//
// I/O mapping (see piano.xdc):
//   clk     -> 100 MHz system clock      (E3)
//   rst     -> BTNC push button          (N17, active high)
//   swt[7:0]-> slide switches SW0..SW7    (the 8 keys)
//   buzzer  -> Pmod JA pin JA1            (C17, drive a passive buzzer/piezo)
//   led     -> LED0                       (H17, flashes at the tone frequency)
//==============================================================================
module piano_top (
    input  wire       clk,
    input  wire       rst,
    input  wire [7:0] swt,
    output wire       buzzer,
    output wire       led
);

    //--------------------------------------------------------------------------
    // Two-stage input synchroniser: brings the asynchronous switch inputs into
    // the clock domain and removes metastability before they are decoded.
    //--------------------------------------------------------------------------
    reg [7:0] key_meta;
    reg [7:0] key_sync;
    always @(posedge clk) begin
        key_meta <= swt;
        key_sync <= key_meta;
    end

    //--------------------------------------------------------------------------
    // Decode the active key into a half-period count for the tone generator.
    //--------------------------------------------------------------------------
    wire [17:0] half_period;
    wire        active;

    note_decoder u_decoder (
        .key         (key_sync),
        .half_period (half_period),
        .active      (active)
    );

    //--------------------------------------------------------------------------
    // Generate the square wave at the selected tone frequency.
    //--------------------------------------------------------------------------
    wire tone;

    tone_generator #(
        .CNT_WIDTH (18)
    ) u_tone (
        .clk         (clk),
        .rst         (rst),
        .enable      (active),
        .half_period (half_period),
        .wave        (tone)
    );

    //--------------------------------------------------------------------------
    // The same square wave drives both the buzzer and the indicator LED, so the
    // LED flashes synchronously with the audible tone. Both are silent/off when
    // no key is pressed because 'tone' is held low while 'active' is low.
    //--------------------------------------------------------------------------
    assign buzzer = tone;
    assign led    = tone;

endmodule
